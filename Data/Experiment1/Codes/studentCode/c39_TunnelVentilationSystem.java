package code;

import java.util.*;

class TunnelAirQuality {
    private double maxCO;
    private double maxNO2;
    private double maxPM25;
    private double currentCO;
    private double currentNO2;
    private double currentPM25;
    private boolean ventilationActive;
    private List<String> log;

    public TunnelAirQuality(double maxCO, double maxNO2, double maxPM25, double initialCO, double initialNO2, double initialPM25) {
        this.maxCO = maxCO;
        this.maxNO2 = maxNO2;
        this.maxPM25 = maxPM25;
        this.currentCO = initialCO;
        this.currentNO2 = initialNO2;
        this.currentPM25 = initialPM25;
        this.ventilationActive = false;
        this.log = new ArrayList<>();
    }

    public void updateAirQuality(double changeCO, double changeNO2, double changePM25) {
        currentCO += changeCO;
        currentNO2 += changeNO2;
        currentPM25 += changePM25;

        String message = String.format("Current Air Quality - CO: %.2f ppm, NO2: %.2f ppm, PM2.5: %.2f µg/m³", 
                                        currentCO, currentNO2, currentPM25);
        
        if (currentCO > maxCO || currentNO2 > maxNO2 || currentPM25 > maxPM25) {
            ventilationActive = true;
            message += " | ALERT: Poor Air Quality! Ventilation System Activated.";
        } else {
            ventilationActive = false;
            message += " | Air Quality is Normal. Ventilation System Standby.";
        }

        System.out.println(message);
        log.add(message);
    }

    public void printLog() {
        System.out.println("\nTunnel Air Quality Log:");
        for (String logEntry : log) {
            System.out.println(logEntry);
        }
    }
}

