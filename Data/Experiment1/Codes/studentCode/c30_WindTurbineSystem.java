package code;

import java.util.*;

class WindTurbine {
    private double maxPower;
    private double minPower;
    private double currentPower;
    private List<String> powerLog;

    public WindTurbine(double maxPower, double minPower, double initialPower) {
        this.maxPower = maxPower;
        this.minPower = minPower;
        this.currentPower = initialPower;
        this.powerLog = new ArrayList<>();
    }

    public void updatePower(double changeAmount) {
        currentPower += changeAmount;

        String message = String.format("Current Power Output: %.1f kW", currentPower);
        if (currentPower > maxPower) {
            message += " | WARNING: Overload Detected! Emergency Shutdown Recommended.";
        } else if (currentPower < minPower) {
            message += " | ALERT: Low Efficiency! Maintenance Recommended.";
        }

        System.out.println(message);
        powerLog.add(message);
    }

    public void printPowerLog() {
        System.out.println("\nPower Output Log:");
        for (String log : powerLog) {
            System.out.println(log);
        }
    }
}

