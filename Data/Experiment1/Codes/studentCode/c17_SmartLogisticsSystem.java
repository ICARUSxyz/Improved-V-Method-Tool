package code;

import java.util.*;

class Shipment {
    private String shipmentId;
    private double currentTemperature;
    private final double minTemp;
    private final double maxTemp;
    private List<String> temperatureLog;

    public Shipment(String shipmentId, double initialTemp, double minTemp, double maxTemp) {
        this.shipmentId = shipmentId;
        this.currentTemperature = initialTemp;
        this.minTemp = minTemp;
        this.maxTemp = maxTemp;
        this.temperatureLog = new ArrayList<>();
        logTemperature("Initialized with temperature: " + initialTemp);
    }

    public void updateTemperature(double newTemp) {
        currentTemperature = newTemp;
        logTemperature("Updated temperature: " + newTemp);

        if (newTemp < minTemp) {
            triggerHeating();
        } else if (newTemp > maxTemp) {
            triggerCooling();
        } else {
            System.out.printf("Shipment %s is within the safe temperature range: %.1f°C%n", shipmentId, newTemp);
        }
    }

    private void triggerHeating() {
        System.out.printf("ALERT! Shipment %s too cold (%.1f°C). Activating heating system!%n", shipmentId, currentTemperature);
        logTemperature("Heating system activated due to low temperature.");
    }

    private void triggerCooling() {
        System.out.printf("ALERT! Shipment %s too hot (%.1f°C). Activating cooling system!%n", shipmentId, currentTemperature);
        logTemperature("Cooling system activated due to high temperature.");
    }

    private void logTemperature(String message) {
        temperatureLog.add(message);
    }

    public void printTemperatureLog() {
        System.out.println("\nTemperature Log for Shipment " + shipmentId + ":");
        for (String log : temperatureLog) {
            System.out.println(log);
        }
    }
}

