package code;

import java.util.*;

class SubwayStation {
    private int maxCapacity;
    private int currentPassengers;
    private int openTurnstiles;
    private List<String> log;

    public SubwayStation(int maxCapacity, int initialPassengers) {
        this.maxCapacity = maxCapacity;
        this.currentPassengers = initialPassengers;
        this.openTurnstiles = 5; 
        this.log = new ArrayList<>();
    }

    public void enterStation(int numPassengers) {
        if (currentPassengers + numPassengers > maxCapacity) {
            System.out.println("WARNING: Station Overcrowded! Entry Restricted.");
            log.add("Overcrowding Alert: Entry Restricted.");
            return;
        }

        currentPassengers += numPassengers;
        adjustTurnstiles();
        System.out.printf("Passengers Entered: %d | Current Count: %d | Open Turnstiles: %d%n", numPassengers, currentPassengers, openTurnstiles);
        log.add(String.format("Entry: %d passengers | New Count: %d | Open Turnstiles: %d", numPassengers, currentPassengers, openTurnstiles));
    }

    public void exitStation(int numPassengers) {
        currentPassengers = Math.max(0, currentPassengers - numPassengers);
        adjustTurnstiles();
        System.out.printf("Passengers Exited: %d | Current Count: %d | Open Turnstiles: %d%n", numPassengers, currentPassengers, openTurnstiles);
        log.add(String.format("Exit: %d passengers | New Count: %d | Open Turnstiles: %d", numPassengers, currentPassengers, openTurnstiles));
    }

    private void adjustTurnstiles() {
        if (currentPassengers > maxCapacity * 0.8) {
            openTurnstiles = 3;
        } else if (currentPassengers < maxCapacity * 0.3) {
            openTurnstiles = 8;
        } else {
            openTurnstiles = 5;
        }
    }

    public void printLog() {
        System.out.println("\nSubway Station Log:");
        for (String logEntry : log) {
            System.out.println(logEntry);
        }
    }
}

